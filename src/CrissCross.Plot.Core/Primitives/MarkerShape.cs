namespace CrissCross.Plot;

/// <summary>Standard markers supported by CrissCross.Plot. See demo app for information about creating custom marker shapes.</summary>
public enum MarkerShape
{
    /// <summary>Does not render a marker.</summary>
    None,

    /// <summary>A filled circle.</summary>
    FilledCircle,

    /// <summary>An outlined circle.</summary>
    OpenCircle,

    /// <summary>A filled square.</summary>
    FilledSquare,

    /// <summary>An outlined square.</summary>
    OpenSquare,

    /// <summary>A filled upward-pointing triangle.</summary>
    FilledTriangleUp,

    /// <summary>An outlined upward-pointing triangle.</summary>
    OpenTriangleUp,

    /// <summary>A filled downward-pointing triangle.</summary>
    FilledTriangleDown,

    /// <summary>An outlined downward-pointing triangle.</summary>
    OpenTriangleDown,

    /// <summary>A filled diamond.</summary>
    FilledDiamond,

    /// <summary>An outlined diamond.</summary>
    OpenDiamond,

    /// <summary>An X-shaped marker.</summary>
    Eks,

    /// <summary>A plus-shaped marker.</summary>
    Cross,

    /// <summary>A vertical bar marker.</summary>
    VerticalBar,

    /// <summary>A horizontal bar marker.</summary>
    HorizontalBar,

    /// <summary>A compact upward-pointing triangle.</summary>
    TriUp,

    /// <summary>A compact downward-pointing triangle.</summary>
    TriDown,

    /// <summary>An asterisk-shaped marker.</summary>
    Asterisk,

    /// <summary>A hash-shaped marker.</summary>
    HashTag,

    /// <summary>An outlined circle with a center dot.</summary>
    OpenCircleWithDot,

    /// <summary>An outlined circle with a plus sign.</summary>
    OpenCircleWithCross,

    /// <summary>An outlined circle with an X.</summary>
    OpenCircleWithEks,

    /// <summary>A circle with a line extending left.</summary>
    CircleWithLineLeft,

    /// <summary>A circle with a line extending right.</summary>
    CircleWithLineRight,

    /// <summary>A triangle with a line extending left.</summary>
    TriangleWithLineLeft,

    /// <summary>A triangle with a line extending right.</summary>
    TriangleWithLineRight
}
