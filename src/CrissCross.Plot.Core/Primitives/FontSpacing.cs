namespace CrissCross.Plot;

/// <summary>Specifies the width class of a font.</summary>
public enum FontSpacing
{
    /// <summary>No font spacing is specified.</summary>
    None = 0,

    /// <summary>The most condensed font width.</summary>
    UltraCondensed = 1,

    /// <summary>An extra-condensed font width.</summary>
    ExtraCondensed = 2,

    /// <summary>A condensed font width.</summary>
    Condensed = 3,

    /// <summary>A semi-condensed font width.</summary>
    SemiCondensed = 4,

    /// <summary>The normal font width.</summary>
    Normal = 5,

    /// <summary>A semi-expanded font width.</summary>
    SemiExpanded = 6,

    /// <summary>An expanded font width.</summary>
    Expanded = 7,

    /// <summary>An extra-expanded font width.</summary>
    ExtraExpanded = 8,

    /// <summary>The most expanded font width.</summary>
    UltraExpanded = 9
}
