namespace CrissCross.Plot;

/// <summary>Specifies the weight of a font.</summary>
public enum FontWeight
{
    /// <summary>An invisible font weight.</summary>
    Invisible = 0,

    /// <summary>A thin font weight.</summary>
    Thin = 100,

    /// <summary>An extra-light font weight.</summary>
    ExtraLight = 200,

    /// <summary>A light font weight.</summary>
    Light = 300,

    /// <summary>A normal font weight.</summary>
    Normal = 400,

    /// <summary>A medium font weight.</summary>
    Medium = 500,

    /// <summary>A semi-bold font weight.</summary>
    SemiBold = 600,

    /// <summary>A bold font weight.</summary>
    Bold = 700,

    /// <summary>An extra-bold font weight.</summary>
    ExtraBold = 800,

    /// <summary>A black font weight.</summary>
    Black = 900,

    /// <summary>An extra-black font weight.</summary>
    ExtraBlack = 1000,
}
