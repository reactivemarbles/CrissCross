namespace CrissCross.Plot;

/// <summary>Identifies a built-in arrow shape.</summary>
public enum ArrowShape
{
    /// <summary>A solid single-line arrow.</summary>
    Single,

    /// <summary>A single-line arrow without a filled head.</summary>
    SingleLine,

    /// <summary>A solid double-ended arrow.</summary>
    Double,

    /// <summary>A double-ended arrow without filled heads.</summary>
    DoubleLine,

    /// <summary>A filled arrowhead.</summary>
    Arrowhead,

    /// <summary>An outlined arrowhead.</summary>
    ArrowheadLine,

    /// <summary>A pentagonal arrow.</summary>
    Pentagon,

    /// <summary>A chevron-shaped arrow.</summary>
    Chevron,
}
