namespace CrissCross.Plot;

/// <summary>Specifies which point of an arrow is anchored to its line.</summary>
public enum ArrowAnchor
{
    /// <summary>Anchors the center of the arrow to the line.</summary>
    Center,

    /// <summary>Anchors the arrow tip to the line.</summary>
    Tip,

    /// <summary>Anchors the arrow tail to the line.</summary>
    Tail,
}
