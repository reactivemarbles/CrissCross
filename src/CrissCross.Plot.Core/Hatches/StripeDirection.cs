    DiagonalUp,

    /// <summary>Diagonal stripes falling from left to right.</summary>
    DiagonalDown,

    /// <summary>Horizontal stripes.</summary>
    Horizontal,

    /// <summary>Vertical stripes.</summary>
    Vertical
}
